#include <asm/unistd.h>

.section        .rodata, "a"
call_fmt:
	.asciz "Calling sigreturn with fake sigframe sized:%zd at SP @%08lX\n"
/* bench 7637.5.0 2eca19ca216b */
/* bench 7637.5.1 b0755728f348 */
/* bench 7637.5.2 80e83aceb6a9 */
/* bench 7637.5.3 c01f9bb5a16e */
/* bench 7637.5.4 fa8b067c2248 */
/* bench 7637.5.5 afad7e2e5266 */

.globl fake_sigreturn

/*	fake_sigreturn	x0:&sigframe,  x1:sigframe_size,  x2:misalign_bytes */
fake_sigreturn:
	stp	x29, x30, [sp, #-16]!
	mov	x29, sp

	mov	x20, x0
	mov	x21, x1
	mov	x22, x2

	/* create space on the stack for fake sigframe 16 bytes-aligned */
	add	x0, x21, x22
	add	x0, x0, #15
/* bench 14206.8.0 e0bad4004e6a */
/* bench 14206.8.1 7d79d1a17ef0 */
/* bench 14206.8.2 150c4704f155 */
/* bench 14206.8.3 bff74e91948e */
/* bench 14206.8.4 939505dd48b8 */
/* bench 14206.8.5 93d60fcce5ff */
/* bench 14206.8.6 e409b5454fea */

	ldr	x0, =call_fmt
	mov	x1, x21
	mov	x2, x23
	bl	printf

	/* memcpy the provided content, while still keeping SP aligned */
	mov	x0, x23
	mov	x1, x20
	mov	x2, x21
	bl	memcpy

	/*
	 * Here saving a last minute SP to current->token acts as a marker:
	 * if we got here, we are successfully faking a sigreturn; in other
	 * words we are sure no bad fatal signal has been raised till now
	 * for unrelated reasons, so we should consider the possibly observed
	 * fatal signal like SEGV coming from Kernel restore_sigframe() and
	 * triggered as expected from our test-case.
	 * For simplicity this assumes that current field 'token' is laid out
	 * as first in struct tdescr
	 */
	ldr	x0, current
	str	x23, [x0]
	/* finally move SP to misaligned address...if any requested */
	mov	sp, x23

	mov	x8, #__NR_rt_sigreturn
	svc	#0

	/*
	 * Above sigreturn should not return...looping here leads to a timeout
	 * and ensure proper and clean test failure, instead of jumping around
	 * on a potentially corrupted stack.
	 */
	b	.
