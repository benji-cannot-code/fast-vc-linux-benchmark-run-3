/* bench 17025.0.1 afb84fcfdcca */
/* bench 17025.0.2 e9b96dc436f6 */
/* bench 17025.0.3 3038a402207d */
/* bench 17025.0.4 5578ee4f4d91 */
/* bench 17025.0.5 5744ee0718a5 */
/* bench 17025.0.6 dacab9554cb0 */
#endif
	stf.spill.nta [dst3] = f0, 64
(p8)	stf.spill.nta [dst_fetch] = f0, L3_LINE_SIZE
	br.cloop.sptk.few 1b
	;;
	mov ar.lc = saved_lc		// restore lc
	br.ret.sptk.many rp
END(clear_page)
EXPORT_SYMBOL(clear_page)
