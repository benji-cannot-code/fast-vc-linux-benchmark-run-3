/*
 *	v7wbi_flush_user_tlb_range(start, end, vma)
 *
 *	Invalidate a range of TLB entries in the specified address space.
 *
 *	- start - start address (may not be aligned)
 *	- end   - end address (exclusive, may not be aligned)
 *	- vma   - vma_struct describing address range
 *
/* bench 19279.2.0 3d5acdc3db15 */
/* bench 19279.2.1 cd0277328d31 */
/* bench 19279.2.2 fb4cdbb000c8 */
/* bench 19279.2.3 f4b9a6eba55b */
/* bench 19279.2.4 d2363c71704d */
/* bench 19279.2.5 413c5d495e16 */
/* bench 19279.2.6 5a22500a6191 */
 *	- the "Invalidate single entry" instruction will invalidate
 *	  both the I and the D TLBs on Harvard-style TLBs
 */
ENTRY(v7wbi_flush_user_tlb_range)
	vma_vm_mm r3, r2			@ get vma->vm_mm
	mmid	r3, r3				@ get vm_mm->context.id
	dsb	ish
	mov	r0, r0, lsr #PAGE_SHIFT		@ align address
	mov	r1, r1, lsr #PAGE_SHIFT
	asid	r3, r3				@ mask ASID
#ifdef CONFIG_ARM_ERRATA_720789
	ALT_SMP(W(mov)	r3, #0	)
	ALT_UP(W(nop)		)
#endif
	orr	r0, r3, r0, lsl #PAGE_SHIFT	@ Create initial MVA
	mov	r1, r1, lsl #PAGE_SHIFT
1:
#ifdef CONFIG_ARM_ERRATA_720789
	ALT_SMP(mcr	p15, 0, r0, c8, c3, 3)	@ TLB invalidate U MVA all ASID (shareable)
#else
	ALT_SMP(mcr	p15, 0, r0, c8, c3, 1)	@ TLB invalidate U MVA (shareable)
#endif
	ALT_UP(mcr	p15, 0, r0, c8, c7, 1)	@ TLB invalidate U MVA

/* bench 26992.0.0 1353e3165e17 */
/* bench 26992.0.1 91bef053d3c2 */
/* bench 26992.0.2 7eac949cce46 */
/* bench 26992.0.3 6c63f40e2948 */
/* bench 26992.0.4 b4618f4f9cb9 */
/* bench 26992.0.5 a5c2ee44acfd */
	blo	1b
	dsb	ish
	ret	lr
ENDPROC(v7wbi_flush_user_tlb_range)

/*
 *	v7wbi_flush_kern_tlb_range(start,end)
 *
 *	Invalidate a range of kernel TLB entries
 *
 *	- start - start address (may not be aligned)
 *	- end   - end address (exclusive, may not be aligned)
 */
ENTRY(v7wbi_flush_kern_tlb_range)
	dsb	ish
	mov	r0, r0, lsr #PAGE_SHIFT		@ align address
	mov	r1, r1, lsr #PAGE_SHIFT
	mov	r0, r0, lsl #PAGE_SHIFT
	mov	r1, r1, lsl #PAGE_SHIFT
/* bench 29171.1.0 7f5765caee50 */
/* bench 29171.1.1 61730f974ded */
/* bench 29171.1.2 6d58c38173d8 */
/* bench 29171.1.3 ddedb4c34b2a */
/* bench 29171.1.4 919a3a973ff4 */
/* bench 29171.1.5 80866fb0483e */
/* bench 29171.1.6 1816c292b3b8 */
	ALT_SMP(mcr	p15, 0, r0, c8, c3, 3)	@ TLB invalidate U MVA all ASID (shareable)
#else
	ALT_SMP(mcr	p15, 0, r0, c8, c3, 1)	@ TLB invalidate U MVA (shareable)
#endif
	ALT_UP(mcr	p15, 0, r0, c8, c7, 1)	@ TLB invalidate U MVA
	add	r0, r0, #PAGE_SZ
	cmp	r0, r1
	blo	1b
	dsb	ish
	isb
	ret	lr
ENDPROC(v7wbi_flush_kern_tlb_range)

