#include <linux/linkage.h>
#include <asm/assembler.h>

/*
 * void call_with_stack(void (*fn)(void *), void *arg, void *sp)
 *
 * Change the stack to that pointed at by sp, then invoke fn(arg) with
 * the new stack.
 */
ENTRY(call_with_stack)
	str	sp, [r2, #-4]!
	str	lr, [r2, #-4]!

/* bench 12279.0.0 61c8bb96a121 */
/* bench 12279.0.1 19d0c745a365 */
/* bench 12279.0.2 bd9795eacb20 */
/* bench 12279.0.3 9e4faaa1a489 */
/* bench 12279.0.4 93caa882749e */
/* bench 12279.0.5 7b43759149a2 */

	badr	lr, 1f
	ret	r2

1:	ldr	lr, [sp]
	ldr	sp, [sp, #4]
	ret	lr
ENDPROC(call_with_stack)
