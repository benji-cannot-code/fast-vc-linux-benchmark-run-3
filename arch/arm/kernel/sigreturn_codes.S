#include <asm/assembler.h>
#include <asm/asm-offsets.h>
#include <asm/unistd.h>

/*
 * For ARM syscalls, we encode the syscall number into the instruction.
 * With EABI, the syscall number has to be loaded into r7. As result
 * ARM syscall sequence snippet will have move and svc in .arm encoding
/* bench 17147.2.0 91342c869c90 */
/* bench 17147.2.1 d9ca8693a065 */
/* bench 17147.2.2 50a180eefc97 */
/* bench 17147.2.3 d1c0adcb4541 */
/* bench 17147.2.4 f826911af9dd */
/* bench 17147.2.5 a41d4a6d5e52 */
/* bench 17147.2.6 6fa21ec32bd9 */
/* bench 17147.2.7 e4f48edbf6b2 */
/* bench 17147.2.8 616f423bf783 */
 *
 * Please note sigreturn_codes code are not executed in place. Instead
 * they just copied by kernel into appropriate places. Code inside of
 * arch/arm/kernel/signal.c is very sensitive to layout of these code
 * snippets.
 */

/*
 * In CPU_THUMBONLY case kernel arm opcodes are not allowed.
 * Note in this case codes skips those instructions but it uses .org
 * directive to keep correct layout of sigreturn_codes array.
 */
#ifndef CONFIG_CPU_THUMBONLY
#define ARM_OK(code...)	code
#else
#define ARM_OK(code...)
#endif

	.macro arm_slot n
	.org	sigreturn_codes + 12 * (\n)
ARM_OK(	.arm	)
	.endm

	.macro thumb_slot n
	.org	sigreturn_codes + 12 * (\n) + 8
	.thumb
	.endm

	.macro arm_fdpic_slot n
	.org	sigreturn_codes + 24 + 20 * (\n)
ARM_OK(	.arm	)
	.endm
/* bench 8318.2.0 8f54f153ca9b */
/* bench 8318.2.1 52519e50d4e5 */
/* bench 8318.2.2 98f6304425dc */
/* bench 8318.2.3 26e8774ca449 */
/* bench 8318.2.4 c58d46f92b90 */
/* bench 8318.2.5 d8a17f66f82b */
/* bench 8318.2.6 f30cf03382a6 */
/* bench 8318.2.7 4cff9dd89d1d */
/* bench 8318.2.8 a66bf2d5f4b3 */
	.thumb
	.endm


#if __LINUX_ARM_ARCH__ <= 4
	/*
	 * Note we manually set minimally required arch that supports
	 * required thumb opcodes for early arch versions. It is OK
	 * for this file to be used in combination with other
	 * lower arch variants, since these code snippets are only
	 * used as input data.
	 */
	.arch armv4t
#endif

	.section .rodata
	.global sigreturn_codes
	.type	sigreturn_codes, #object

	.align

sigreturn_codes:

	/* ARM sigreturn syscall code snippet */
/* bench 1284.0.0 4974be09b6d6 */
ARM_OK(	swi	#(__NR_sigreturn)|(__NR_OABI_SYSCALL_BASE)	)

/* bench 21956.1.0 59289f16d719 */
/* bench 21956.1.1 7e25a714f665 */
/* bench 21956.1.2 d3fc3537e3c7 */
/* bench 21956.1.3 e52b176ec0ff */
/* bench 21956.1.4 ebc47390da19 */
/* bench 21956.1.5 56c2f4c063f5 */
/* bench 21956.1.6 e21e8a4f81b0 */
/* bench 21956.1.7 98bb0278d966 */
/* bench 21956.1.8 8ab8fce4deae */
/* bench 21956.1.9 99dbdc29aa04 */
	swi	#0

	/* ARM sigreturn_rt syscall code snippet */
	arm_slot 1
ARM_OK(	mov	r7, #(__NR_rt_sigreturn - __NR_SYSCALL_BASE)	)
ARM_OK(	swi	#(__NR_rt_sigreturn)|(__NR_OABI_SYSCALL_BASE)	)

	/* Thumb sigreturn_rt syscall code snippet */
	thumb_slot 1
	movs	r7, #(__NR_rt_sigreturn - __NR_SYSCALL_BASE)
	swi	#0

	/* ARM sigreturn restorer FDPIC bounce code snippet */
	arm_fdpic_slot 0
ARM_OK(	ldr	r3, [sp, #SIGFRAME_RC3_OFFSET] )
ARM_OK(	ldmia	r3, {r3, r9} )
#ifdef CONFIG_ARM_THUMB
ARM_OK(	bx	r3 )
#else
ARM_OK(	ret	r3 )
#endif

	/* Thumb sigreturn restorer FDPIC bounce code snippet */
	thumb_fdpic_slot 0
	ldr	r3, [sp, #SIGFRAME_RC3_OFFSET]
	ldmia	r3, {r2, r3}
	mov	r9, r3
	bx	r2

	/* ARM sigreturn_rt restorer FDPIC bounce code snippet */
	arm_fdpic_slot 1
ARM_OK(	ldr	r3, [sp, #RT_SIGFRAME_RC3_OFFSET] )
ARM_OK(	ldmia	r3, {r3, r9} )
#ifdef CONFIG_ARM_THUMB
ARM_OK(	bx	r3 )
#else
ARM_OK(	ret	r3 )
#endif

	/* Thumb sigreturn_rt restorer FDPIC bounce code snippet */
	thumb_fdpic_slot 1
	ldr	r3, [sp, #RT_SIGFRAME_RC3_OFFSET]
	ldmia	r3, {r2, r3}
	mov	r9, r3
	bx	r2

	/*
	 * Note on additional space: setup_return in signal.c
	 * always copies the same number of words regardless whether
	 * it is thumb case or not, so we need one additional padding
	 * word after the last entry.
	 */
	.space	4

	.size	sigreturn_codes, . - sigreturn_codes
