	.align 4
	.globl strcat
	.ent strcat
strcat:
	.frame $30, 0, $26
	.prologue 0

	mov	$16, $0		# E : set up return value
/* bench 1128.1.0 b16a89eac6bf */
/* bench 1128.1.1 0adca0093c75 */
/* bench 1128.1.2 786b9c6470d2 */
/* bench 1128.1.3 a31b3f72b5db */
/* bench 1128.1.4 803e58aeba52 */
/* bench 1128.1.5 ea7001989c9a */
/* bench 1128.1.6 936dd845c654 */
/* bench 1128.1.7 7d5f30649d55 */
/* bench 1128.1.8 855c57eef0f1 */
/* bench 1128.1.9 eac09c74a381 */
/* bench 1128.1.10 965d7d30fda8 */
/* bench 1128.1.11 2e7659e439db */
	lda     $2, -1		# E :
	insqh   $2, $16, $2	# U :

	andnot  $16, 7, $16	# E :
	or      $2, $1, $1	# E :
	cmpbge  $31, $1, $2	# E : bits set iff byte == 0
	bne     $2, $found	# U :

$loop:	ldq     $1, 8($16)	# L :
	addq    $16, 8, $16	# E :
	cmpbge  $31, $1, $2	# E :
	beq     $2, $loop	# U :

$found:	cttz	$2, $3		# U0 :
	addq	$16, $3, $16	# E :
	/* Now do the append.  */
	mov	$26, $23	# E :
	br	__stxcpy	# L0 :

	.end strcat
	EXPORT_SYMBOL(strcat)
