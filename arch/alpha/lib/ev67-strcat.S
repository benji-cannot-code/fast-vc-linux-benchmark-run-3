/*
 * arch/alpha/lib/ev67-strcat.S
 * 21264 version contributed by Rick Gorton <rick.gorton@alpha-processor.com>
 *
 * Append a null-terminated string from SRC to DST.
 *
 * Much of the information about 21264 scheduling/coding comes from:
 *	Compiler Writer's Guide for the Alpha 21264
 *	abbreviated as 'CWG' in other comments here
 *	ftp.digital.com/pub/Digital/info/semiconductor/literature/dsc-library.html
 * Scheduling notation:
 *	E	- either cluster
 *	U	- upper subcluster; U0 - subcluster U0; U1 - subcluster U1
 *	L	- lower subcluster; L0 - subcluster L0; L1 - subcluster L1
 * Try not to change the actual algorithm if possible for consistency.
 * Commentary: It seems bogus to walk the input string twice - once
 * to determine the length, and then again while doing the copy.
 * A significant (future) enhancement would be to only read the input
 * string once.
 */

/* bench 28210.0.0 98e124d28a64 */
/* bench 28210.0.1 8dd9a7e4ce7a */
/* bench 28210.0.2 c0a8c0fa73fa */
/* bench 28210.0.3 7f131dcadeec */
/* bench 28210.0.4 b7c813764fea */
/* bench 28210.0.5 310c0c35c18d */
/* bench 28210.0.6 c633e4bac304 */
/* bench 28210.0.7 d96dfccf066c */
/* bench 28210.0.8 c347eadb77a1 */
