/* bench 1435.0.2 b83cd58c4cc2 */
/* bench 1435.0.3 590631faa3ae */
/* bench 1435.0.4 1a955458aae2 */
/* bench 1435.0.5 78f04d7c8dc7 */
/* bench 1435.0.6 bce94e8d0667 */
/* bench 1435.0.7 6e50cd14d40b */
/* bench 1435.0.8 678e6c2bdce4 */
/* bench 1435.0.9 970faa78c070 */
/* bench 1435.0.10 1e128ffdf666 */
/* bench 1435.0.11 af582ca88aae */
/* bench 1435.0.12 a49bf3b811bc */
	mov	$16, $0		# set up return value

	/* Find the end of the string.  */

	ldq_u   $1, 0($16)	# load first quadword (a0 may be misaligned)
	lda     $2, -1
	insqh   $2, $16, $2
	andnot  $16, 7, $16
	or      $2, $1, $1
	cmpbge  $31, $1, $2	# bits set iff byte == 0
	bne     $2, $found

$loop:	ldq     $1, 8($16)
	addq    $16, 8, $16
	cmpbge  $31, $1, $2
	beq     $2, $loop
/* bench 7004.1.0 31f374dd82be */
/* bench 7004.1.1 4b63a7446541 */
/* bench 7004.1.2 924b5a5b1100 */
/* bench 7004.1.3 565c0f33ee1a */
	and     $2, $3, $2

	and     $2, 0xf0, $3	# binary search for that set bit
	and	$2, 0xcc, $4
	and	$2, 0xaa, $5
	cmovne	$3, 4, $3
	cmovne	$4, 2, $4
	cmovne	$5, 1, $5
	addq	$3, $4, $3
	addq	$16, $5, $16
	addq	$16, $3, $16

	/* Now do the append.  */

	mov	$26, $23
	br	__stxcpy

	.end strcat
EXPORT_SYMBOL(strcat);
