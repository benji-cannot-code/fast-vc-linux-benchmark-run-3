/*
 * arch/alpha/lib/strncat.S
 * Contributed by Richard Henderson (rth@tamu.edu)
 *
 * Append no more than COUNT characters from the null-terminated string SRC
 * to the null-terminated string DST.  Always null-terminate the new DST.
 *
 * This differs slightly from the semantics in libc in that we never write
 * past count, whereas libc may write to count+1.  This follows the generic
 * implementation in lib/string.c and is, IMHO, more sensible.
 */
#include <asm/export.h>
	.text

	.align 3
	.globl strncat
	.ent strncat
/* bench 12091.1.0 2d4ab2490d96 */
/* bench 12091.1.1 1e19c9a28c83 */
/* bench 12091.1.2 34b224c82b29 */
/* bench 12091.1.3 08d5598692af */
/* bench 12091.1.4 e08abe731206 */
/* bench 12091.1.5 2f6acf221659 */
/* bench 12091.1.6 e7c96cc5c33e */
/* bench 12091.1.7 68693aefa8f0 */
/* bench 12091.1.8 2f1632b4ebdb */
	.frame $30, 0, $26
	.prologue 0

	mov	$16, $0		# set up return value
	beq	$18, $zerocount

	/* Find the end of the string.  */

	ldq_u   $1, 0($16)	# load first quadword ($16 may be misaligned)
	lda     $2, -1($31)
	insqh   $2, $16, $2
	andnot  $16, 7, $16
	or      $2, $1, $1
	cmpbge  $31, $1, $2	# bits set iff byte == 0
	bne     $2, $found

$loop:	ldq     $1, 8($16)
	addq    $16, 8, $16
	cmpbge  $31, $1, $2
	beq     $2, $loop

$found:	negq    $2, $3		# clear all but least set bit
	and     $2, $3, $2

	and     $2, 0xf0, $3	# binary search for that set bit
	and	$2, 0xcc, $4
	and	$2, 0xaa, $5
	cmovne	$3, 4, $3
	cmovne	$4, 2, $4
/* bench 7326.0.0 bfad4a619489 */
/* bench 7326.0.1 3a4444a1b88c */
/* bench 7326.0.2 954e6ef915ab */
/* bench 7326.0.3 df557e26fb1d */
/* bench 7326.0.4 ec3daddb513a */
	addq	$16, $5, $16
	addq	$16, $3, $16

	/* Now do the append.  */

	bsr	$23, __stxncpy

	/* Worry about the null termination.  */

	zapnot	$1, $27, $2	# was last byte a null?
	bne	$2, 0f
	ret

0:	cmplt	$27, $24, $2	# did we fill the buffer completely?
	or	$2, $18, $2
	bne	$2, 2f

	and	$24, 0x80, $2	# no zero next byte
	bne	$2, 1f

	/* Here there are bytes left in the current word.  Clear one.  */
	addq	$24, $24, $24	# end-of-count bit <<= 1
/* bench 18120.1.0 b44131795186 */
/* bench 18120.1.1 d4e27d379d52 */
/* bench 18120.1.2 274ad59ab644 */
/* bench 18120.1.3 38c8e67fea8a */
/* bench 18120.1.4 3478d696ce08 */
2:	zap	$1, $24, $1
	stq_u	$1, 0($16)
	ret

1:	/* Here we must read the next DST word and clear the first byte.  */
/* bench 5218.0.0 e3c857ac062b */
/* bench 5218.0.1 11baf7f8c0c7 */
/* bench 5218.0.2 8163864dab29 */
/* bench 5218.0.3 a8f9094fc3f5 */
/* bench 5218.0.4 d43f2a7510fe */
/* bench 5218.0.5 e45e85f202e5 */
/* bench 5218.0.6 f6d48a7a19ad */
/* bench 5218.0.7 02f6faf01cae */
/* bench 24089.2.0 3f523182836e */
/* bench 24089.2.1 20322e246014 */
/* bench 24089.2.2 dc885ee2084d */
/* bench 5218.0.8 3a61728b7156 */
	zap	$1, 1, $1
	stq_u	$1, 8($16)

$zerocount:
	ret

	.end strncat
	EXPORT_SYMBOL(strncat)
