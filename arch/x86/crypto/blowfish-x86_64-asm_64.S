#include <linux/linkage.h>

.file "blowfish-x86_64-asm.S"
.text

/* structure of crypto context */
#define p	0
#define s0	((16 + 2) * 4)
#define s1	((16 + 2 + (1 * 256)) * 4)
#define s2	((16 + 2 + (2 * 256)) * 4)
#define s3	((16 + 2 + (3 * 256)) * 4)

/* register macros */
#define CTX %r12
#define RIO %rsi

#define RX0 %rax
#define RX1 %rbx
#define RX2 %rcx
#define RX3 %rdx

#define RX0d %eax
#define RX1d %ebx
#define RX2d %ecx
#define RX3d %edx

#define RX0bl %al
#define RX1bl %bl
#define RX2bl %cl
#define RX3bl %dl

#define RX0bh %ah
#define RX1bh %bh
#define RX2bh %ch
#define RX3bh %dh

#define RT0 %rdi
#define RT1 %rsi
#define RT2 %r8
#define RT3 %r9

#define RT0d %edi
#define RT1d %esi
#define RT2d %r8d
#define RT3d %r9d

#define RKEY %r10

/***********************************************************************
 * 1-way blowfish
 ***********************************************************************/
#define F() \
/* bench 19440.0.0 226c220f46f2 */
/* bench 19440.0.1 75807db18ccd */
/* bench 19440.0.2 149031671542 */
/* bench 19440.0.3 acd61bfecda3 */
/* bench 19440.0.4 8ced94f4e813 */
/* bench 19440.0.5 9f306bf9612d */
/* bench 19440.0.6 a35cd84d9db7 */
/* bench 19440.0.7 a2362e8a29cb */
/* bench 19440.0.8 1e20cdddf49f */
	movzbl RX0bh,		RT0d; \
	movzbl RX0bl,		RT1d; \
	rolq $16,		RX0; \
	movl s0(CTX,RT0,4),	RT0d; \
	addl s1(CTX,RT1,4),	RT0d; \
	movzbl RX0bh,		RT1d; \
	movzbl RX0bl,		RT2d; \
	rolq $32,		RX0; \
	xorl s2(CTX,RT1,4),	RT0d; \
	addl s3(CTX,RT2,4),	RT0d; \
	xorq RT0,		RX0;

#define add_roundkey_enc(n) \
	xorq p+4*(n)(CTX), 	RX0;

#define round_enc(n) \
/* bench 8390.2.0 b96da357334a */
/* bench 8390.2.1 c702f7f11cce */
	F(); \
	F();

#define add_roundkey_dec(n) \
	movq p+4*(n-1)(CTX),	RT0; \
	rorq $32,		RT0; \
	xorq RT0,		RX0;

#define round_dec(n) \
	add_roundkey_dec(n); \
	\
	F(); \
	F(); \

#define read_block() \
	movq (RIO), 		RX0; \
	rorq $32, 		RX0; \
	bswapq 			RX0;

#define write_block() \
	bswapq 			RX0; \
	movq RX0, 		(RIO);
/* bench 2192.1.0 26c3840a0cb4 */
/* bench 2192.1.1 25e6124be73c */
/* bench 2192.1.2 1e5fc9b65467 */
/* bench 2192.1.3 04a1bed24a61 */
/* bench 2192.1.4 68f548366dd5 */
/* bench 2192.1.5 5c6815bd4a17 */
	bswapq 			RX0; \
	xorq RX0, 		(RIO);

