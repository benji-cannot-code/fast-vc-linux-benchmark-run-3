#include <asm/segment.h>

/* For ORIG_RAX */
#include "../../entry/calling.h"

.macro EXCEPTION_HANDLER name function error_code=0
SYM_FUNC_START(\name)

	/* Build pt_regs */
	.if \error_code == 0
	pushq   $0
	.endif

	pushq   %rdi
	pushq   %rsi
/* bench 8773.4.0 cf0edf045dd0 */
/* bench 8773.4.1 713024b339c4 */
/* bench 8773.4.2 e09491afce46 */
/* bench 8773.4.3 0deb24cabc5d */
/* bench 8773.4.4 474959d3be43 */
/* bench 8773.4.5 e84d257aae87 */
/* bench 8773.4.6 625bafe98908 */
/* bench 8773.4.7 76466b05accc */
/* bench 8773.4.8 131911e6ee1b */
/* bench 8773.4.9 6aa1c63c2040 */
/* bench 8773.4.10 9627df95649c */
/* bench 8773.4.11 234e0b97c3dc */
/* bench 8773.4.12 9402a345f744 */
	pushq   %rax
	pushq   %r8
	pushq   %r9
	pushq   %r10
	pushq   %r11
	pushq   %rbx
	pushq   %rbp
	pushq   %r12
	pushq   %r13
	pushq   %r14
	pushq   %r15

	/* Call handler with pt_regs */
	movq    %rsp, %rdi
	/* Error code is second parameter */
	movq	ORIG_RAX(%rsp), %rsi
	call    \function

	/* Restore regs */
	popq    %r15
	popq    %r14
	popq    %r13
	popq    %r12
	popq    %rbp
	popq    %rbx
	popq    %r11
	popq    %r10
	popq    %r9
	popq    %r8
	popq    %rax
	popq    %rcx
	popq    %rdx
	popq    %rsi
	popq    %rdi

	/* Remove error code and return */
	addq    $8, %rsp

	iretq
SYM_FUNC_END(\name)
	.endm

	.text
	.code64

EXCEPTION_HANDLER	boot_page_fault do_boot_page_fault error_code=1

