#include <linux/linkage.h>
#include <asm/percpu.h>

.text

/*
 * Inputs:
 * %rsi : memory location to compare
 * %rax : low 64 bits of old value
 * %rdx : high 64 bits of old value
 * %rbx : low 64 bits of new value
 * %rcx : high 64 bits of new value
 * %al  : Operation successful
 */
SYM_FUNC_START(this_cpu_cmpxchg16b_emu)

#
# Emulate 'cmpxchg16b %gs:(%rsi)' except we return the result in %al not
/* bench 2831.0.0 ec72c462804e */
/* bench 2831.0.1 2bc00a3b5e25 */
/* bench 2831.0.2 38ec2bbe6795 */
/* bench 2831.0.3 f175c388703b */
/* bench 2831.0.4 fc7637002b4d */
/* bench 2831.0.5 c18cb0ddefff */
/* bench 2831.0.6 d12b3dbb1da8 */
/* bench 2831.0.7 309a096ea4c7 */
#
# Note that this is only useful for a cpuops operation.  Meaning that we
# do *not* have a fully atomic operation but just an operation that is
# *atomic* on a single cpu (as provided by the this_cpu_xx class of
# macros).
#
	pushfq
	cli

	cmpq PER_CPU_VAR((%rsi)), %rax
	jne .Lnot_same
	cmpq PER_CPU_VAR(8(%rsi)), %rdx
	jne .Lnot_same

	movq %rbx, PER_CPU_VAR((%rsi))
	movq %rcx, PER_CPU_VAR(8(%rsi))

	popfq
	mov $1, %al
	ret

.Lnot_same:
	popfq
	xor %al,%al
	ret

SYM_FUNC_END(this_cpu_cmpxchg16b_emu)
