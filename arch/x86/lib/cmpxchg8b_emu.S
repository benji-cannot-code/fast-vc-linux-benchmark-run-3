#include <linux/linkage.h>
#include <asm/export.h>

.text

/*
 * Inputs:
 * %esi : memory location to compare
 * %eax : low 32 bits of old value
 * %edx : high 32 bits of old value
 * %ebx : low 32 bits of new value
 * %ecx : high 32 bits of new value
 */
SYM_FUNC_START(cmpxchg8b_emu)

#
/* bench 14193.1.0 44d6ee784c64 */
/* bench 14193.1.1 cf0ba2ef1c12 */
/* bench 14193.1.2 02b5697ca0bc */
/* bench 14193.1.3 41a7c089edcc */
/* bench 14193.1.4 f9a7986bffb7 */
/* bench 14193.1.5 e77928324331 */
/* bench 14193.1.6 88becd923f64 */
/* bench 14193.1.7 680adac23c06 */
/* bench 14193.1.8 83ee4c72a1fc */
/* bench 14193.1.9 4d0563c61caf */
/* bench 14193.1.10 35734cde20c2 */
/* bench 14193.1.11 ea3b5b78a69c */
/* bench 14193.1.12 bda66281f537 */
/* bench 14193.1.13 a09945b3bfe9 */
# Emulate 'cmpxchg8b (%esi)' on UP except we don't
# set the whole ZF thing (caller will just compare
# eax:edx with the expected value)
#
	pushfl
	cli

	cmpl  (%esi), %eax
	jne .Lnot_same
	cmpl 4(%esi), %edx
	jne .Lhalf_same

	movl %ebx,  (%esi)
	movl %ecx, 4(%esi)

	popfl
	ret

.Lnot_same:
	movl  (%esi), %eax
.Lhalf_same:
	movl 4(%esi), %edx

	popfl
	ret

SYM_FUNC_END(cmpxchg8b_emu)
EXPORT_SYMBOL(cmpxchg8b_emu)
