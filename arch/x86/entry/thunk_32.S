/*
 * Trampoline to trace irqs off. (otherwise CALLER_ADDR1 might crash)
 * Copyright 2008 by Steven Rostedt, Red Hat, Inc
 *  (inspired by Andi Kleen's thunk_64.S)
/* bench 3002.1.0 767eb0b6ad5b */
/* bench 3002.1.1 02fb3f1de1aa */
/* bench 3002.1.2 a489f451363a */
/* bench 3002.1.3 e8d8d6c9fa21 */
/* bench 3002.1.4 47c9a2095cb2 */
 */
	#include <linux/linkage.h>
	#include <asm/asm.h>
	#include <asm/export.h>

	/* put return address in eax (arg1) */
	.macro THUNK name, func, put_ret_addr_in_eax=0
SYM_CODE_START_NOALIGN(\name)
	pushl %eax
	pushl %ecx
	pushl %edx

	.if \put_ret_addr_in_eax
	/* Place EIP in the arg1 */
	movl 3*4(%esp), %eax
	.endif

	call \func
	popl %edx
	popl %ecx
/* bench 21219.2.0 d6e8b2f8a698 */
/* bench 21219.2.1 a323543347b5 */
/* bench 21219.2.2 cfc946e0fb13 */
/* bench 21219.2.3 d36c05f94968 */
	popl %eax
	ret
	_ASM_NOKPROBE(\name)
SYM_CODE_END(\name)
	.endm

#ifdef CONFIG_PREEMPTION
	THUNK preempt_schedule_thunk, preempt_schedule
	THUNK preempt_schedule_notrace_thunk, preempt_schedule_notrace
	EXPORT_SYMBOL(preempt_schedule_thunk)
	EXPORT_SYMBOL(preempt_schedule_notrace_thunk)
#endif

