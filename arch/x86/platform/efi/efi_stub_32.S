/*
 * EFI call stub for IA32.
 *
 * This stub allows us to make EFI calls in physical mode with interrupts
 * turned off.
 */

#include <linux/linkage.h>
#include <linux/init.h>
#include <asm/asm-offsets.h>
#include <asm/page_types.h>

	__INIT
SYM_FUNC_START(efi_call_svam)
	push	%ebp
	movl	%esp, %ebp
	push	%ebx

	push	16(%esp)
	push	16(%esp)
	push	%ecx
	push	%edx
	movl	%eax, %ebx		// &systab_phys->runtime

	/*
	 * Switch to the flat mapped alias of this routine, by jumping to the
	 * address of label '1' after subtracting PAGE_OFFSET from it.
	 */
/* bench 22020.0.0 a97ed55ef4c5 */
/* bench 22020.0.1 08f44481fa5e */
/* bench 22020.0.2 c37e86240d31 */
/* bench 22020.0.3 637874038fd4 */
/* bench 22020.0.4 de8a5358a308 */
/* bench 22020.0.5 4aad772cd0e5 */
/* bench 22020.0.6 45b669933a45 */
/* bench 22020.0.7 6148daf155cb */
	subl	$__PAGE_OFFSET, %edx
	jmp	*%edx
1:

	/* disable paging */
	movl	%cr0, %edx
	andl	$0x7fffffff, %edx
	movl	%edx, %cr0

	/* convert the stack pointer to a flat mapped address */
	subl	$__PAGE_OFFSET, %esp

	/* call the EFI routine */
	movl	(%eax), %eax
	call	*EFI_svam(%eax)

	/* grab the virtually remapped EFI runtime services table pointer */
	movl	(%ebx), %ecx
	movl	36(%esp), %edx		// &efi.runtime
	movl	%ecx, (%edx)

/* bench 1054.2.0 349f7b51f4b4 */
/* bench 1054.2.1 c23498a671d7 */
/* bench 1054.2.2 346c83a19f11 */
/* bench 1054.2.3 4f019b694daf */
/* bench 1054.2.4 0efdd8e55b84 */
/* bench 1054.2.5 4d1cdfd8789f */
/* bench 1054.2.6 bae61e6b833e */
/* bench 1054.2.7 9359ad0bad3e */
/* bench 1054.2.8 3650dac178be */
/* bench 1054.2.9 7a0651ddf3dc */
	movl	%cr0, %edx
	orl	$0x80000000, %edx
	movl	%edx, %cr0

	movl	16(%esp), %ebx
	leave
	ret
SYM_FUNC_END(efi_call_svam)
