; numerator in A0/A1
; denominator in A2/A3
	.global	__modsi3
__modsi3:
	PUSHP	S2P
	bsr	modnorm
	bsr	__divsi3
	mov.l	er3,er0
	bra	exitdiv

	.global	__umodsi3
__umodsi3:
	bsr	__udivsi3
	mov.l	er3,er0
	rts

	.global	__divsi3
__divsi3:
	PUSHP	S2P
	jsr	divnorm
	bsr	__udivsi3

	; examine what the sign should be
exitdiv:
	btst	#3,S2L
