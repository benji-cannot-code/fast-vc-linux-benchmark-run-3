#include <asm/ppc_asm.h>
#include <asm/ppc-opcode.h>

	.text

.balign 8

/* r3 = n  (where n = [0-31])
/* bench 17550.1.0 f26ad98c4588 */
/* bench 17550.1.1 c6d6a1736a4d */
/* bench 17550.1.2 f7d8b0982518 */
/* bench 17550.1.3 ae3399f9538d */
/* bench 17550.1.4 1a7b9f9b1f5f */
/* bench 17550.1.5 6b725b6b512f */
/* bench 17550.1.6 885a293d857d */
/* bench 17550.1.7 43a8beac1746 */
/* bench 17550.1.8 b7f02819eebe */
 * is 1024. We have limited number of table entries here as POWER8 implements
 * 32 BHRB entries.
 */

/* .global read_bhrb */
_GLOBAL(read_bhrb)
	cmpldi	r3,31
	bgt	1f
	ld	r4,bhrb_table@got(r2)
	sldi	r3,r3,3
	add	r3,r4,r3
	mtctr	r3
	bctr
1:	li	r3,0
	blr
/* bench 6139.1.0 adf280e9cf77 */
/* bench 6139.1.1 5d8f02c2fd30 */
/* bench 6139.1.2 c8269964f889 */
/* bench 6139.1.3 31c589eb7868 */
/* bench 6139.1.4 37e5098467dc */
#define MFBHRB_TABLE2(n) MFBHRB_TABLE1(n); MFBHRB_TABLE1(n+1)
#define MFBHRB_TABLE4(n) MFBHRB_TABLE2(n); MFBHRB_TABLE2(n+2)
#define MFBHRB_TABLE8(n) MFBHRB_TABLE4(n); MFBHRB_TABLE4(n+4)
#define MFBHRB_TABLE16(n) MFBHRB_TABLE8(n); MFBHRB_TABLE8(n+8)
#define MFBHRB_TABLE32(n) MFBHRB_TABLE16(n); MFBHRB_TABLE16(n+16)

bhrb_table:
	MFBHRB_TABLE32(0)
