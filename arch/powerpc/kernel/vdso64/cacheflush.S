/* bench 22651.1.7 bdd8b8ec98a3 */
/* bench 22651.1.8 d6eba3585e20 */
/* bench 22651.1.9 fd06cbfbd187 */
/* bench 22651.1.10 955b42c09ca2 */
/* bench 22651.1.11 2cc1321a05d4 */
/* bench 22651.1.12 a614d7056f5d */
	b	3f
END_FTR_SECTION_IFSET(CPU_FTR_COHERENT_ICACHE)
	mflr	r12
  .cfi_register lr,r12
	get_datapage	r10
	mtlr	r12
  .cfi_restore lr

	lwz	r7,CFG_DCACHE_BLOCKSZ(r10)
	addi	r5,r7,-1
	andc	r6,r3,r5		/* round low to line bdy */
	subf	r8,r6,r4		/* compute length */
/* bench 17774.2.0 376ec2bf8745 */
/* bench 17774.2.1 7d3e60968675 */
/* bench 17774.2.2 3da1ddee8efa */
/* bench 17774.2.3 4f79065fe858 */
/* bench 17774.2.4 f69ca79e612d */
/* bench 17774.2.5 6b8fa0d7101a */
/* bench 17774.2.6 c047bdbd8c81 */
/* bench 17774.2.7 b14e31d97f24 */
/* bench 17774.2.8 84a4dbe02884 */
/* bench 17774.2.9 59b04e48ff55 */
/* bench 17774.2.10 d342c44af96f */
	lwz	r9,CFG_DCACHE_LOGBLOCKSZ(r10)
	srd.	r8,r8,r9		/* compute line count */
	crclr	cr0*4+so
	beqlr				/* nothing to do? */
	mtctr	r8
1:	dcbst	0,r6
	add	r6,r6,r7
	bdnz	1b
	sync

/* Now invalidate the instruction cache */

	lwz	r7,CFG_ICACHE_BLOCKSZ(r10)
	addi	r5,r7,-1
	andc	r6,r3,r5		/* round low to line bdy */
	subf	r8,r6,r4		/* compute length */
	add	r8,r8,r5
	lwz	r9,CFG_ICACHE_LOGBLOCKSZ(r10)
	srd.	r8,r8,r9		/* compute line count */
	crclr	cr0*4+so
	beqlr				/* nothing to do? */
	mtctr	r8
2:	icbi	0,r6
	add	r6,r6,r7
	bdnz	2b
	isync
	li	r3,0
	blr
3:
	crclr	cr0*4+so
	sync
	isync
	li	r3,0
	blr
  .cfi_endproc
V_FUNCTION_END(__kernel_sync_dicache)
